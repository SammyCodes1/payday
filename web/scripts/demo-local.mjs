#!/usr/bin/env node
// LOCAL DEMO ONLY. Starts anvil on 127.0.0.1:8545, deploys MockUSDC + the real SpendPolicy from ../out,
// allow-lists three demo payees, funds the policy with 10,000 mock USDC and writes .env.local
// (fresh random SESSION_SECRET / CRON_SECRET; anvil accounts from Foundry's PUBLIC test mnemonic).
// Keep it running, then `npm run dev` in another terminal and import anvil account #0 into your
// browser wallet to sign in as the owner. Never point this at a real network.
import { spawn } from "node:child_process";
import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createPublicClient, createWalletClient, http, stringToHex } from "viem";
import { mnemonicToAccount } from "viem/accounts";
import { foundry } from "viem/chains";

const ROOT = join(import.meta.dirname, "..", "..");
const PORT = Number(process.env.ANVIL_PORT ?? 8545);
const RPC = `http://127.0.0.1:${PORT}`;
const MNEMONIC = "test test test test test test test test test test test junk"; // public Foundry dev mnemonic
const acct = (i) => mnemonicToAccount(MNEMONIC, { addressIndex: i });
const U = 1_000_000n;
const art = (f, n) => {
  const j = JSON.parse(readFileSync(join(ROOT, "out", f, `${n}.json`), "utf8"));
  return { abi: j.abi, bytecode: j.bytecode.object };
};
const cat = (s) => stringToHex(s, { size: 32 });

const anvil = spawn("anvil", ["--host", "127.0.0.1", "--port", String(PORT), "--chain-id", "31337"], { stdio: ["ignore", "ignore", "inherit"] });
process.on("SIGINT", () => { anvil.kill(); process.exit(0); });
const pc = createPublicClient({ chain: foundry, transport: http(RPC), pollingInterval: 250 });
for (let i = 0; i < 100; i++) { try { await pc.getChainId(); break; } catch { await new Promise((r) => setTimeout(r, 100)); } }

const owner = createWalletClient({ account: acct(0), chain: foundry, transport: http(RPC) });
const wait = (hash) => pc.waitForTransactionReceipt({ hash });
const tok = art("MockUSDC.sol", "MockUSDC");
const usdc = (await wait(await owner.deployContract({ abi: tok.abi, bytecode: tok.bytecode }))).contractAddress;
const sp = art("SpendPolicy.sol", "SpendPolicy");
const deploy = await wait(await owner.deployContract({ abi: sp.abi, bytecode: sp.bytecode, args: [usdc, acct(0).address, acct(2).address, 1000n * U, 5000n * U, 20000n * U, 7n * 86400n] }));
const policy = deploy.contractAddress;
const w = async (functionName, args) => wait(await owner.writeContract({ address: policy, abi: sp.abi, functionName, args }));
for (const c of ["RENT", "SUPPLIES", "REPAIRS"]) await w("setCategoryBudget", [cat(c), 3000n * U]);
await w("setPayee", [acct(3).address, "Adebayo Properties", cat("RENT"), 0n]);
await w("setPayee", [acct(4).address, "Lagos Paper Co", cat("SUPPLIES"), 0n]);
await w("setPayee", [acct(5).address, "Chidi Generator Repairs", cat("REPAIRS"), 3000n * U]);
await wait(await owner.writeContract({ address: usdc, abi: tok.abi, functionName: "mint", args: [policy, 10_000n * U] }));

writeFileSync(join(import.meta.dirname, "..", ".env.local"), [
  "# generated by scripts/demo-local.mjs for LOCAL anvil only - do not commit",
  "PAYDAY_CHAIN=anvil", `PAYDAY_RPC_URL=${RPC}`, `PAYDAY_POLICY_ADDRESS=${policy}`, `PAYDAY_POLICY_DEPLOY_BLOCK=${deploy.blockNumber}`,
  "PAYDAY_EXECUTOR=local", "PAYDAY_LLM_PROVIDER=mock", `SESSION_SECRET=${randomBytes(32).toString("hex")}`,
  `CRON_SECRET=${randomBytes(32).toString("hex")}`, "PAYDAY_APP_ORIGIN=http://localhost:3000", "PAYDAY_DB_PATH=./data/demo.sqlite",
  "NEXT_PUBLIC_CHAIN=anvil", `NEXT_PUBLIC_RPC_URL=${RPC}`, "NEXT_PUBLIC_EXPLORER_URL=http://localhost:3000/stats", "",
].join("\n"));
console.log(`anvil ${RPC} | policy ${policy} | usdc ${usdc}`);
console.log("wrote .env.local. Run `npm run dev` in another terminal; Ctrl+C here stops anvil.");

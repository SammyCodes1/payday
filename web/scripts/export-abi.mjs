// Copies the SpendPolicy + SpendPolicyFactory ABIs from the Foundry build (../out) into src/lib.
// Run `forge build` in the repo root first. The contract sources are never modified.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..", "..");
const lib = path.resolve(import.meta.dirname, "../src/lib");
function emit(sol, name, constName, file) {
  const artifact = JSON.parse(fs.readFileSync(path.join(root, `out/${sol}/${name}.json`), "utf8"));
  const out = `// AUTO-GENERATED by scripts/export-abi.mjs from out/${sol}/${name}.json. Do not edit.
export const ${constName} = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
  fs.writeFileSync(path.join(lib, file), out);
  console.log(`wrote src/lib/${file} with`, artifact.abi.length, "entries");
}
emit("SpendPolicy.sol", "SpendPolicy", "spendPolicyAbi", "abi.ts");
emit("SpendPolicyFactory.sol", "SpendPolicyFactory", "spendPolicyFactoryAbi", "factory-abi.ts");

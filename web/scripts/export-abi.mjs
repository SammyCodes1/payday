// Copies the SpendPolicy ABI from the Foundry build (../out) into src/lib/abi.ts.
// Run `forge build` in the repo root first. The contract source is never modified.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..", "..");
const artifact = JSON.parse(fs.readFileSync(path.join(root, "out/SpendPolicy.sol/SpendPolicy.json"), "utf8"));
const out = `// AUTO-GENERATED by scripts/export-abi.mjs from out/SpendPolicy.sol/SpendPolicy.json. Do not edit.
export const spendPolicyAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
fs.writeFileSync(path.resolve(import.meta.dirname, "../src/lib/abi.ts"), out);
console.log("wrote src/lib/abi.ts with", artifact.abi.length, "entries");
